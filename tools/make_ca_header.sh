#!/usr/bin/env bash
# Project Atlas - embed the laboratory CA certificate into the firmware
# AT-26-L1-002
#
# The ESP32 has no certificate store. The one authority it trusts is compiled
# into the image, which is the correct arrangement for a private laboratory PKI:
# the device trusts exactly one issuer and nothing else, so a certificate from
# any public authority - or from an attacker who obtains one - is rejected.
#
# ca.crt is public material and safe to commit; ca.key is not and must never be
# copied into the firmware tree.
#
# Run from the repository root:  ./tools/make_ca_header.sh

set -euo pipefail

SRC="infra/mosquitto/certs/ca.crt"
DST="firmware/atlas-node/include/ca_cert.h"

[[ -f "$SRC" ]] || { echo "no $SRC - run from the repository root"; exit 1; }
mkdir -p "$(dirname "$DST")"

{
  echo "// Generated by tools/make_ca_header.sh - do not edit by hand."
  echo "// Source: $SRC"
  echo "// Regenerate whenever the certificate authority is replaced."
  echo "#pragma once"
  echo
  echo "static const char ATLAS_CA_CERT[] PROGMEM = R\"EOF("
  cat "$SRC"
  echo ")EOF\";"
} > "$DST"

echo "wrote $DST"
openssl x509 -in "$SRC" -noout -subject -enddate
